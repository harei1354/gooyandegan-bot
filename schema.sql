-- Run in Supabase SQL Editor before starting the bot.
create table if not exists public.posts (
 id bigint generated by default as identity primary key,
 user_id bigint not null, chat_id bigint not null, thread_id bigint not null default 0,
 category text not null, content_hash text not null, created_at timestamptz not null default now()
);
create index if not exists posts_quota_idx on public.posts(user_id, category, created_at desc);
create index if not exists posts_hash_idx on public.posts(content_hash);
create table if not exists public.moderation (
 user_id bigint not null, chat_id bigint not null, strikes integer not null default 0,
 updated_at timestamptz not null default now(), primary key(user_id, chat_id)
);
create table if not exists public.submissions (
 id bigint generated by default as identity primary key, user_id bigint not null,
 username text not null default '', content text not null, status text not null default 'pending',
 reviewed_by bigint, created_at timestamptz not null default now()
);
-- The bot uses the service-role key, which must remain private and server-side.
